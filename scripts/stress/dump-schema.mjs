// Rebuild the PRODUCTION schema (no rows) as plain DDL, from catalog reads only.
// Uses the Management API read-only query endpoint (q.mjs). Writes dump/schema.sql.
// Why: the access token has no database_write, so `supabase db dump` (login role) is refused.
// Usage: node scripts/stress/dump-schema.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { q as rawQ } from './q.mjs';

const q = (sql) => rawQ(`set search_path to pg_catalog; ${sql}`);
const out = [];
const emit = (s) => out.push(s.trim().endsWith(';') ? s : s + ';');
const qi = (s) => (/^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s.replace(/"/g, '""')}"`);
const PUB = `relnamespace = 'public'::regnamespace`;

out.push('-- Generated by scripts/stress/dump-schema.mjs from production catalogs (schema only, no rows).');
out.push('set check_function_bodies = off;');
out.push('set search_path = public, extensions;');
for (const e of ['vector', 'pgcrypto', '"uuid-ossp"']) emit(`create extension if not exists ${e} with schema extensions`);

// 1. Sequences (not identity-owned)
const seqs = await q(`select c.relname, format_type(s.seqtypid,null) typ, s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache, s.seqcycle
  from pg_sequence s join pg_class c on c.oid = s.seqrelid
  where c.${PUB} and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i') order by 1`);
for (const s of seqs) emit(`create sequence if not exists public.${qi(s.relname)} as ${s.typ} increment ${s.seqincrement} minvalue ${s.seqmin} maxvalue ${s.seqmax} start ${s.seqstart} cache ${s.seqcache}${s.seqcycle ? ' cycle' : ''}`);

// 2. Tables (columns, identity, generated; defaults later)
const cols = await q(`select c.relname, a.attnum, a.attname, format_type(a.atttypid,a.atttypmod) typ, a.attnotnull, a.attidentity, a.attgenerated,
    pg_get_expr(d.adbin, d.adrelid) def, c.relrowsecurity rls, c.relforcerowsecurity frls
  from pg_class c join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
  where c.${PUB} and c.relkind = 'r' order by c.relname, a.attnum`);
const tables = new Map();
for (const r of cols) { if (!tables.has(r.relname)) tables.set(r.relname, []); tables.get(r.relname).push(r); }
const defaults = [];
for (const [t, cs] of tables) {
  const lines = cs.map((c) => {
    let l = `  ${qi(c.attname)} ${c.typ}`;
    if (c.attidentity === 'a') l += ' generated always as identity';
    else if (c.attidentity === 'd') l += ' generated by default as identity';
    else if (c.attgenerated === 's') l += ` generated always as (${c.def}) stored`;
    else if (c.def != null) defaults.push(`alter table public.${qi(t)} alter column ${qi(c.attname)} set default ${c.def}`);
    if (c.attnotnull) l += ' not null';
    return l;
  });
  emit(`create table public.${qi(t)} (\n${lines.join(',\n')}\n)`);
}

// 3. Sequence ownership
const owned = await q(`select c.relname seq, t.relname tab, a.attname col from pg_depend d
  join pg_class c on c.oid = d.objid and c.relkind = 'S' join pg_class t on t.oid = d.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where d.deptype = 'a' and c.${PUB}`);
const ownedSql = owned.map((o) => `alter sequence public.${qi(o.seq)} owned by public.${qi(o.tab)}.${qi(o.col)}`);

// 4. Views (deferred if they fail; the SQL runner tolerates order by re-running the file twice)
const views = await q(`select c.relname, pg_get_viewdef(c.oid, true) def, to_json(c.reloptions) reloptions from pg_class c where c.${PUB} and c.relkind in ('v','m') order by 1`);
const viewSql = views.map((v) => `create or replace view public.${qi(v.relname)}${v.reloptions ? ` with (${v.reloptions.join(', ')})` : ''} as\n${v.def.replace(/;\s*$/, '')}`);
viewSql.forEach(emit);

// 5. Functions
const fns = await q(`select p.oid, pg_get_functiondef(p.oid) def from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p')
  and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') order by p.proname`);
for (const f of fns) emit(f.def.trim());
out.push('-- views again, now that functions exist');
viewSql.forEach(emit);

// 6. Defaults, sequence ownership
defaults.forEach(emit);
ownedSql.forEach(emit);

// 7. Constraints (p, u, c, x first; f last)
const cons = await q(`select c.relname, k.conname, k.contype, pg_get_constraintdef(k.oid, true) def
  from pg_constraint k join pg_class c on c.oid = k.conrelid where c.${PUB} and c.relkind = 'r'
  order by case k.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 when 'x' then 3 else 4 end, c.relname, k.conname`);
for (const k of cons) emit(`alter table public.${qi(k.relname)} add constraint ${qi(k.conname)} ${k.def}`);

// 8. Indexes not backing a constraint
const idx = await q(`select pg_get_indexdef(i.indexrelid) def from pg_index i join pg_class c on c.oid = i.indexrelid
  where c.${PUB} and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid) order by 1`);
for (const i of idx) emit(i.def);

// 9. Triggers (public tables + auth.users)
const trg = await q(`select pg_get_triggerdef(t.oid) def from pg_trigger t join pg_class c on c.oid = t.tgrelid
  where not t.tgisinternal and (c.${PUB} or (c.relname = 'users' and c.relnamespace = 'auth'::regnamespace and t.tgname = 'on_auth_user_created')) order by 1`);
for (const t of trg) emit(t.def);

// 10. RLS + policies (public + storage.objects)
for (const [t, cs] of tables) {
  if (cs[0].rls) emit(`alter table public.${qi(t)} enable row level security`);
  if (cs[0].frls) emit(`alter table public.${qi(t)} force row level security`);
}
const pols = await q(`select n.nspname sch, c.relname, p.polname, p.polpermissive, p.polcmd,
    to_json(array(select case when r = 0 then 'public' else (select rolname from pg_roles where oid = r) end from unnest(p.polroles) r)) roles,
    pg_get_expr(p.polqual, p.polrelid) qual, pg_get_expr(p.polwithcheck, p.polrelid) chk
  from pg_policy p join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public','storage') order by 1, 2, 3`);
const CMD = { r: 'select', a: 'insert', w: 'update', d: 'delete', '*': 'all' };
out.push('-- storage.objects policies: drop local ones of the same name first');
for (const p of pols) {
  const tgt = `${p.sch}.${qi(p.relname)}`;
  if (p.sch === 'storage') emit(`drop policy if exists ${qi(p.polname)} on ${tgt}`);
  emit(`create policy ${qi(p.polname)} on ${tgt} as ${p.polpermissive ? 'permissive' : 'restrictive'} for ${CMD[p.polcmd]} to ${p.roles.map((r) => (r === 'public' ? 'public' : qi(r))).join(', ')}${p.qual ? ` using (${p.qual})` : ''}${p.chk ? ` with check (${p.chk})` : ''}`);
}

// 11. Grants — revoke the local defaults first, then replay production ACLs exactly
const ROLES = ['anon', 'authenticated', 'service_role'];
const rels = await q(`select c.relname, c.relkind, coalesce((select json_agg(json_build_object('g', case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee) end, 'p', a.privilege_type))
    from aclexplode(c.relacl) a), '[]'::json) acl, c.relacl is null nullacl
  from pg_class c where c.${PUB} and c.relkind in ('r','v','m','S') order by 1`);
for (const r of rels) {
  const kind = r.relkind === 'S' ? 'sequence' : 'table';
  emit(`revoke all on ${kind} public.${qi(r.relname)} from public, ${ROLES.join(', ')}`);
  for (const a of r.acl) if (a.g === 'public' || ROLES.includes(a.g)) emit(`grant ${a.p} on ${kind} public.${qi(r.relname)} to ${a.g}`);
}
const colAcl = await q(`select c.relname, a.attname, x.privilege_type p, (select rolname from pg_roles where oid = x.grantee) g
  from pg_attribute a join pg_class c on c.oid = a.attrelid cross join aclexplode(a.attacl) x where c.${PUB} and a.attacl is not null`);
for (const a of colAcl) if (ROLES.includes(a.g)) emit(`grant ${a.p} (${qi(a.attname)}) on table public.${qi(a.relname)} to ${a.g}`);
const fnAcl = await q(`select p.oid::regprocedure::text sig, p.proacl is null nullacl,
    coalesce((select json_agg(case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee) end) from aclexplode(p.proacl) a where a.privilege_type = 'EXECUTE'), '[]'::json) g
  from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p')
  and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')`);
for (const f of fnAcl) {
  emit(`revoke all on function ${f.sig} from public, ${ROLES.join(', ')}`);
  const gs = f.nullacl ? ['public'] : f.g;
  for (const g of gs) if (g === 'public' || ROLES.includes(g)) emit(`grant execute on function ${f.sig} to ${g}`);
}

// 12. Storage buckets (ids + public flag only)
const buckets = await rawQ(`select id, public, file_size_limit, allowed_mime_types from storage.buckets`);
for (const b of buckets) emit(`insert into storage.buckets (id, name, public) values ('${b.id}', '${b.id}', ${b.public}) on conflict (id) do nothing`);

out.push('notify pgrst, \'reload schema\';');
const file = path.join(path.dirname(fileURLToPath(import.meta.url)), 'dump', 'schema.sql');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out.join('\n\n') + '\n');
console.log(`wrote ${file}: ${tables.size} tables, ${views.length} views, ${fns.length} functions, ${cons.length} constraints, ${idx.length} indexes, ${trg.length} triggers, ${pols.length} policies`);
